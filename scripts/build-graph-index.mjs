#!/usr/bin/env node
// Regenerates the retrieval indexes under CONTEXT/.
// One line per node: link | title | status | one sentence. Nothing else.
// Run: make graph-index (or: make graph-index-check)

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const CONTEXT = join(ROOT, 'CONTEXT')
const CHECK = process.argv.includes('--check')
const CHECK_LINKS = process.argv.includes('--check-links')

/** A node whose status says the work is over. Anything else stays live. */
const SETTLED = (node) => /^(shipped|cut|done|closed|wontfix|superseded)\b/.test(node.status)

const GROUPS = [
  {
    file: 'index.md',
    title: 'index — durable knowledge',
    sections: [
      { heading: 'Product contract', dir: 'product' },
      { heading: 'Operational setup', dir: 'operations' },
    ],
  },
  {
    file: 'index-issues.md',
    title: 'index — issues (open work)',
    sections: [{ heading: 'Open issues', dir: 'issues', reject: SETTLED }],
  },
  {
    file: 'index-issues-closed.md',
    title: 'index — issues (shipped & cut)',
    sections: [{ heading: 'Settled issues', dir: 'issues', accept: SETTLED }],
  },
  {
    file: 'index-handoffs.md',
    title: 'index — handoffs (session history)',
    sections: [{ heading: 'Handoffs', dir: 'handoffs' }],
  },
]

/** First `# ` heading, with a filename fallback. */
function title(body, fallback) {
  const match = body.match(/^#\s+(.+)$/m)
  return match ? match[1].trim() : fallback.replace(/\.md$/, '')
}

/** Supports plain and bold Markdown metadata near the top of a node. */
function status(body) {
  const match = body.slice(0, 800).match(/^\s*(?:[-*]\s+)?\*{0,2}Status\*{0,2}\s*:\s*\*{0,2}\s*(.+)$/mi)
  return match ? match[1].trim().toLowerCase() : ''
}

/** First real sentence of prose, capped so the index stays cheap to read. */
function summary(body) {
  const lines = body.split('\n')
  const prose = []
  for (const raw of lines) {
    const line = raw.trim()
    if (!line) {
      if (prose.length) break
      continue
    }
    if (line.startsWith('#')) {
      if (prose.length) break
      continue
    }
    if (/^-?\s*(?:\*\*)?(Status|Date|Blocked by|Depends on|Owner|Verification-command)(?:\*\*)?:/i.test(line)) continue
    if (/^\((condensed|full spec)/i.test(line)) continue
    if (/^[-*|>]/.test(line)) continue
    prose.push(line)
  }
  let text = prose.join(' ').replace(/\s+/g, ' ')
  text = text.replace(/\*\*(.+?)\*\*/g, '$1').replace(/`(.+?)`/g, '$1')
  const dot = text.search(/\.\s/)
  if (dot > 30) text = text.slice(0, dot + 1)
  if (text.length > 150) text = text.slice(0, 147).replace(/\s\S*$/, '') + '…'
  return text || '(no summary)'
}

function nodesIn(section) {
  const dir = join(CONTEXT, section.dir)
  if (!existsSync(dir)) return []
  const nodes = readdirSync(dir)
    .filter((name) => name.endsWith('.md'))
    .sort()
    .map((name) => {
      const body = readFileSync(join(dir, name), 'utf8')
      const link = relative(CONTEXT, join(dir, name))
      return { link, title: title(body, name), status: status(body), summary: summary(body) }
    })
  if (section.accept) return nodes.filter(section.accept)
  if (section.reject) return nodes.filter((node) => !section.reject(node))
  return nodes
}

function render(group) {
  const output = [`# ${group.title}`, '', '<!-- GENERATED by scripts/build-graph-index.mjs — do not hand-edit. -->', '']
  for (const section of group.sections) {
    const nodes = nodesIn(section)
    if (!nodes.length) continue
    output.push(`## ${section.heading} (${nodes.length})`, '')
    for (const node of nodes) {
      const tag = node.status ? ` [${node.status}]` : ''
      output.push(`- [[${node.link}|${node.title}]]${tag} — ${node.summary}`)
    }
    output.push('')
  }
  return output.join('\n')
}

let failed = false
let drift = 0

if (!CHECK_LINKS) {
  for (const group of GROUPS) {
    const path = join(CONTEXT, group.file)
    const next = render(group)
    const previous = existsSync(path) ? readFileSync(path, 'utf8') : ''
    if (previous === next) continue
    if (CHECK) {
      console.error(`stale: CONTEXT/${group.file}`)
      drift++
    } else {
      writeFileSync(path, next)
      console.log(`wrote CONTEXT/${group.file}`)
    }
  }
  if (CHECK && drift) {
    console.error(`\n${drift} index file(s) stale. Run: make graph-index`)
    failed = true
  }
}

function checkLinks() {
  let checked = 0
  const broken = []
  for (const group of GROUPS) {
    const path = join(CONTEXT, group.file)
    if (!existsSync(path)) {
      broken.push(`CONTEXT/${group.file} (missing generated index)`)
      continue
    }
    const body = readFileSync(path, 'utf8')
    for (const match of body.matchAll(/\[\[([^|\]]+)(?:\|[^\]]+)?\]\]/g)) {
      const target = match[1].split('#', 1)[0]
      checked++
      if (!existsSync(join(CONTEXT, target))) broken.push(`CONTEXT/${group.file} → ${target}`)
    }
  }
  console.log(`links: checked ${checked}, broken ${broken.length}`)
  for (const link of broken) console.error(`broken: ${link}`)
  return broken.length
}

if (checkLinks() > 0) failed = true
if (CHECK && !failed) console.log('indexes current')
if (failed) process.exit(1)
